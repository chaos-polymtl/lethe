"""
Postprocessing code for the Reynolds number sweep of the 2D backward-facing step
Computes the reattachment length (x_r) on the final mesh of every case of the sweep
(generated by generate_cases_locally.py) and compares it with the benchmark data of
benchmark-data.txt.
"""

import argparse
import os
import re

import matplotlib.pyplot as plt
import numpy as np

from compute_reattachment_length import output_files, reattachment_length

# Plot font and colors
font = {'weight' : 'normal',
        'size'   : 13}
plt.rc('font', **font)
colors = ['#1b9e77','#d95f02','#7570b3','#e7298a','#66a61e','#e6ab02']

SWEEP_FOLDER = 'reynolds_sweep'
CASE_PATTERN = re.compile(r'Re_(\d+)$')
BENCHMARK_FILE = 'benchmark-data.txt'


def read_benchmark_data(filename):
    """
    Read the benchmark data file, in which every data set starts with a comment line
    of the form "# - AUTHOR (YEAR) -" followed by lines "Re x_r".
    Returns a dictionary {name: (Re, x_r)}.
    """
    data = {}
    name = None
    with open(filename) as f:
        for line in f:
            header = re.match(r'#\s*-\s*(.+?)\s*-\s*$', line)
            if header:
                name = header.group(1).title().replace(' And ', ' and ')
                data[name] = ([], [])
            elif line.strip() and not line.startswith('#') and name is not None:
                Re, x_r = map(float, line.split()[:2])
                data[name][0].append(Re)
                data[name][1].append(x_r)
    return {name: (np.array(Re), np.array(x_r)) for name, (Re, x_r) in data.items()}


parser = argparse.ArgumentParser(description='Post-processing of the Reynolds number sweep of the backward-facing step')
parser.add_argument("--validate", action="store_true", help="Launches the script in validation mode. This will log the content of the graph and prevent the display of figures", default=False)
args, leftovers = parser.parse_known_args()

# Reattachment length on the final mesh of every case
reynolds, cells, x_r = [], [], []
for case in sorted(os.listdir(SWEEP_FOLDER)):
    match = CASE_PATTERN.match(case)
    if not match:
        continue
    n_cells, x_reattachment = reattachment_length(output_files(os.path.join(SWEEP_FOLDER, case))[-1])
    reynolds.append(int(match.group(1)))
    cells.append(n_cells)
    x_r.append(x_reattachment)
reynolds, cells, x_r = np.array(reynolds), np.array(cells), np.array(x_r)
order = np.argsort(reynolds)
reynolds, cells, x_r = reynolds[order], cells[order], x_r[order]

# Comparison with the numerical benchmark of Erturk (2008)
benchmark = read_benchmark_data(BENCHMARK_FILE)
Re_erturk, x_r_erturk = benchmark['Erturk (2008)']
x_r_reference = np.interp(reynolds, Re_erturk, x_r_erturk, left=np.nan, right=np.nan)
relative_error = (x_r - x_r_reference) / x_r_reference

for Re, n, x, x_ref, error in zip(reynolds, cells, x_r, x_r_reference, relative_error):
    print(f"Re = {Re:5d} ({n:7d} cells): x_r = {x:.4f}, Erturk (2008) = {x_ref:.4f}, relative error = {error:+.4f}")

# Plot the reattachment length and its relative error with respect to Erturk (2008)
fig0, (ax0, ax1) = plt.subplots(2, 1, sharex=True, figsize=(6.4, 7.2), gridspec_kw={'height_ratios': [2, 1]})
ax0.plot(Re_erturk, x_r_erturk, lw=2, ls='--', color=colors[0], label="Erturk (2008)")
markers = {'Armaly (1983)': '^', 'Velivelli and Bryden (2015)': 's'}
for i, (name, (Re_ref, x_ref)) in enumerate(item for item in benchmark.items() if item[0] != 'Erturk (2008)'):
    ax0.plot(Re_ref, x_ref, markers.get(name, 'o'), mfc='None', mew=2, ms=8, color=colors[i+1], label=name)
ax0.plot(reynolds, x_r, 'ko-', lw=2, ms=6, label="Lethe")
ax0.set_ylabel(r"$x_r$ [-]")
ax0.legend(loc='upper left')

ax1.axhline(0, color=colors[0], lw=2, ls='--')
ax1.plot(reynolds, 100 * relative_error, 'ko-', lw=2, ms=6)
ax1.set_xlabel(r"$\mathrm{Re}$ [-]")
ax1.set_ylabel("Error vs Erturk [%]")
fig0.tight_layout()

if (not args.validate):
    fig0.savefig("reynolds-sweep.png", dpi=300)
    plt.show()

else:
    # Store the plotted data so that they can be compared between validation runs
    np.savetxt("solution-reattachment-length-sweep.dat",
               np.column_stack((reynolds, cells, x_r, x_r_reference, relative_error)),
               header="Re cells x_r x_r_Erturk relative_error")
    fig0.savefig("lethe-reattachment-length-sweep.pdf")
