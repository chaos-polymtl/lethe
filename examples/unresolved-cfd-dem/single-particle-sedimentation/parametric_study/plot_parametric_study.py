"""
Script to plot the results of the parametric study of the single particle
sedimentation example. It must be launched from the parametric_study folder
once all the cases generated by generate_cases.py have been simulated. It plots
the particle velocity and the void fraction along the particle trajectory for
all the meshes (one panel per L2 smoothing length) and saves the figures as
terminal_velocity.png and voidfraction_convergence.png.
"""

import glob
import os
import re
import sys

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.ticker import FormatStrFormatter, MaxNLocator

sys.path.append("../")

from single_particle_sedimentation_funcs import *
define_plot_style()

convert_m_to_cm = 100

# Data (identical to single_particle_sedimentation.py)
dp = 0.002663
rhop = 1029.
nu = 0.0000008379
rhof = 996.7775
mu = nu * rhof
g = -9.81
dt = 0.05
t_end = 2
initial_position = 0.08

# Width of the domain in number of particle diameters
domain_width_over_dp = 20

# Time window of the zoomed view of the velocity and height range of the void
# fraction plots
velocity_zoom_time = [1.0, 1.2]
void_fraction_height_range = [0, 6]

# Style of the zoomed views
inset_line_width = 2
inset_font_size = 18

# Find the cases and sort them by smoothing length and mesh size
cases = {}
for folder in glob.glob("case_nx_*_Ldp_*"):
    match = re.search(r"case_nx_(\d+)_Ldp_(\d+)", os.path.basename(folder))
    if match:
        n = int(match.group(1))
        l = int(match.group(2))
        cases.setdefault(l, []).append(n)

if not cases:
    sys.exit("No case found. Run generate_cases.py and launch_cases.sh first.")

l2_over_dp = sorted(cases)
n_cells = sorted(cases[l2_over_dp[0]], reverse=True)
panel_letters = "abcdefghijklmnopqrstuvwxyz"

analytical_time, analytical_velocity, analytical_position = analytical_solution(
    dp, rhop, rhof, mu, g, dt, t_end, initial_position)


def mesh_label(n):
    return rf"$S_c/d_p = {domain_width_over_dp / n:.2f}$"


# Particle velocity as a function of time
fig, axes = plt.subplots(1, len(l2_over_dp), figsize=(20, 5.6))
for ax, l, letter in zip(np.atleast_1d(axes), l2_over_dp, panel_letters):
    axins = ax.inset_axes([0.17, 0.27, 0.33, 0.4])
    zoom_values = []
    for n in n_cells:
        time, velocity = get_time_and_velocity_from_simulation(
            f"case_nx_{n}_Ldp_{l}/output/result__particles.pvd")
        time = np.asarray(time)
        for a in [ax, axins]:
            a.plot(time, -velocity * convert_m_to_cm, label=mesh_label(n))
        in_zoom = (time >= velocity_zoom_time[0]) & (time <= velocity_zoom_time[1])
        zoom_values.extend(-velocity[in_zoom] * convert_m_to_cm)

    for a in [ax, axins]:
        a.plot(analytical_time, -analytical_velocity * convert_m_to_cm, "k--",
               label="Analytical")
    in_zoom = (analytical_time >= velocity_zoom_time[0]) & (
        analytical_time <= velocity_zoom_time[1])
    zoom_values.extend(-analytical_velocity[in_zoom] * convert_m_to_cm)

    margin = 0.1 * (max(zoom_values) - min(zoom_values))
    axins.set_xlim(velocity_zoom_time)
    axins.set_ylim(min(zoom_values) - margin, max(zoom_values) + margin)
    axins.set_xticklabels([])
    axins.set_yticklabels([])
    ax.indicate_inset_zoom(axins, edgecolor="black", alpha=1,
                           linewidth=inset_line_width)

    ax.set_title(rf"{letter}) $L/d_p = {l}$", loc="left")
    ax.set_xlabel("Time [s]")
    ax.set_ylabel("Velocity [cm/s]")
    ax.legend(loc="lower right")
plt.savefig("terminal_velocity.png", dpi=300)
plt.close()

# Void fraction along the particle trajectory at the end of the simulation
fig, axes = plt.subplots(1, len(l2_over_dp), figsize=(20, 5.6), sharey=True)
for ax, l, letter in zip(np.atleast_1d(axes), l2_over_dp, panel_letters):
    for n in n_cells:
        time, sample = get_center_void_fraction_from_simulation(
            f"case_nx_{n}_Ldp_{l}/output/result_.pvd")
        ax.plot(sample.points[:, 1] * convert_m_to_cm, sample["void_fraction"],
                label=mesh_label(n))

    ax.set_xlim(void_fraction_height_range)
    ax.set_title(rf"{letter}) $L/d_p = {l}$", loc="left")
    ax.set_xlabel("Height [cm]")
    ax.legend(loc="lower left", ncol=2)
np.atleast_1d(axes)[0].set_ylabel("Void fraction [-]")

# Leave room below the largest void fraction drop for the legends
largest_depth = max(1 - np.min(line.get_ydata())
                    for ax in np.atleast_1d(axes) for line in ax.get_lines())
np.atleast_1d(axes)[0].set_ylim(1 - 2 * largest_depth, 1 + 0.05 * largest_depth)

# Zoom on the void fraction drop when it is small compared to the axis range
y_min, y_max = np.atleast_1d(axes)[0].get_ylim()
for ax in np.atleast_1d(axes):
    lines = ax.get_lines()
    minimum = min(np.min(line.get_ydata()) for line in lines)
    depth = 1 - minimum
    if depth > 0.2 * (y_max - y_min):
        continue
    height_at_minimum = [line.get_xdata()[np.argmin(line.get_ydata())]
                         for line in lines]
    center = np.mean(height_at_minimum)
    axins = ax.inset_axes([0.55, 0.4, 0.4, 0.38])
    for line in lines:
        axins.plot(line.get_xdata(), line.get_ydata(), color=line.get_color())
    axins.set_xlim(center - 1, center + 1)
    axins.set_ylim(minimum - 0.1 * depth, 1 + 0.1 * depth)
    axins.set_xticklabels([])
    axins.yaxis.set_major_locator(MaxNLocator(2))
    axins.yaxis.set_major_formatter(FormatStrFormatter("%.4f"))
    axins.tick_params(labelsize=inset_font_size)
    ax.indicate_inset_zoom(axins, edgecolor="black", alpha=1,
                           linewidth=inset_line_width)
plt.savefig("voidfraction_convergence.png", dpi=300)
plt.close()

print("Figures saved: terminal_velocity.png and voidfraction_convergence.png")
