#ifndef lethe_grid_pipe_and_waveguide_h
#define lethe_grid_pipe_and_waveguide_h

#include <deal.II/base/utilities.h>

#include <deal.II/grid/grid_generator.h>
#include <deal.II/grid/grid_tools.h>
#include <deal.II/grid/manifold_lib.h>

#include <array>
#include <sstream>

using namespace dealii;

/**
 * @brief Generates a 3D mesh of a waveguide embedded in a cylindrical cavity in which a liquid flows
 *
 * The geometry consists of three sections joined along the z-axis:
 * - A bottom cylinder
 * - A central cylinder into which the rectangular-based waveguide is embedded
 * - A top cylinder
 *
 * Note that the mesh of the cylinder is inspired from the hyper_ball function
 * of the deal.II library.
 *
 * Boundary IDs are assigned as follows:
 * -0: Waveguide port (end face of the waveguide at x = 0)
 * -1: Bottom surface of the cylinder (z = -bottom_height)
 * -2: Top surface of the cylinder (z = middle_height + top_height)
 * -3: Lateral wall of the cylinder
 * -4: Lateral walls of the waveguide
 *
 * Material IDs are assigned as follows:
 * -0: Cylinder
 * -1: Waveguide (paving stone)
 *
 * A CylindricalManifold (manifold id 1) is attached to the cells of the
 * cylinder that have a face on its lateral wall, so that mesh refinement
 * preserves the shape of the cylinder. In the middle section, this includes
 * the face shared by the cylinder and the waveguide, which therefore follows
 * the lateral wall of the cylinder. With an inner circle, the manifold is set
 * on the whole cell, so that the inner circle is also preserved. With an inner
 * square, it is only set on the face on the lateral wall, so that the sides of
 * the square stay straight. The cells of the waveguide keep the flat manifold.
 *
 * @tparam dim The dimension of the mesh, must be 3.
 * @tparam spacedim The dimension of the space, must be 3.
 */

template <int dim, int spacedim>
class GridPipeAndWaveguide

{
public:
  /**
   * @brief Constructor that parses grid parameters from a colon-separated
   * string.
   *
   * @param[in] grid_arguments A string with the following format:
   * @code "rectangle_width : rectangle_length : outer_radius : inner_length :
   * bottom_height : middle_height : top_height : bottom_resolution :
   * middle_resolution : top_resolution : inner_circle" @endcode
   *
   * | #   | Field             | Format        | Required | Description                                                                                              |
   * |-----|-------------------|---------------|----------|----------------------------------------------------------------------------------------------------------|
   * |  0  | rectangle_width   | double        | yes      | Waveguide width                                                                                          |
   * |  1  | rectangle_length  | double        | yes      | Waveguide length                                                                                         |
   * |  2  | outer_radius      | double        | yes      | Radius of the main cylinder                                                                              |
   * |  3  | inner_length      | double        | yes      | Depending on the inner shape, it is the radius of the inner circle or the half-side of the inner square  |
   * |  4  | bottom_height     | double        | yes      | Height of the bottom cylinder                                                                            |
   * |  5  | middle_height     | double        | yes      | Height of the waveguide                                                                                  |
   * |  6  | top_height        | double        | yes      | Height of the top cylinder                                                                               |
   * |  7  | bottom_resolution | unsigned int  | yes      | Number of slices generated by the extrusion of the bottom cylinder (at least 2)                          |
   * |  8  | middle_resolution | unsigned int  | yes      | Number of slices generated by the extrusion of the center cylinder (at least 2)                          |
   * |  9  | top_resolution    | unsigned int  | yes      | Number of slices generated by the extrusion of the top cylinder (at least 2)                             |
   * |  10 | inner_circle      | true/false    | no       | True (default): The inner shape is a circle False: Inner square                                          |
   * Example: @code "0.07 : 0.05 : 0.1 : 0.07 : 0.1 : 0.07 : 0.1 : 3 : 2 : 3 :
   * true" @endcode
   */
  GridPipeAndWaveguide(const std::string &grid_arguments);

  /**
   * @brief Generate a cylindrical fluid conduit in which a block-shaped waveguide is embedded.
   *
   * The three parts of the geometry (bottom cylinder, center_cylinder (with the
   * waveguide), top cylinder) are first merged and returned coarse
   *
   * @param[in,out] triangulation The triangulation to fill with the mesh.
   */

  void
  make_grid(Triangulation<dim, spacedim> &triangulation);

  /// Boundary id of the waveguide port (end face of the waveguide at x = 0)
  static constexpr types::boundary_id waveguide_port_boundary_id = 0;

  /// Boundary id of the bottom surface of the cylinder
  static constexpr types::boundary_id bottom_boundary_id = 1;

  /// Boundary id of the top surface of the cylinder
  static constexpr types::boundary_id top_boundary_id = 2;

  /// Boundary id of the lateral wall of the cylinder
  static constexpr types::boundary_id cylinder_wall_boundary_id = 3;

  /// Boundary id of the lateral walls of the waveguide
  static constexpr types::boundary_id waveguide_wall_boundary_id = 4;

  /// Material id of the cells of the cylinder
  static constexpr types::material_id cylinder_material_id = 0;

  /// Material id of the cells of the waveguide
  static constexpr types::material_id waveguide_material_id = 1;

  /// Manifold id of the CylindricalManifold of the cylinder
  static constexpr types::manifold_id cylindrical_manifold_id = 1;

private:
  /**
   * @brief The function detailed_circle is a tool used in the core of the file
   *
   * This function is an extension of the 2D part of the hyper_ball in-built
   * deal.ii function.
   *
   * Since the deal.ii merge function needs the two trangulations to have
   * overlapped points, we needed to produce a coarse circular mesh with two
   * points at the exact place where the rectangle would fit. This is why this
   * function was created.
   *
   * There are three main differences between hyper_ball and detailed_circle:
   *
   * -Fourteen points were added to the mesh (8 points in the original one)
   * to link the circle with the rectangle we want to merge and to
   * prevent triangular cells from being generated.
   *
   * - A central rectangle of width equal to the waveguide width crosses the
   * circle along the x-axis. This minimizes the aspect ratio of the cells
   * contained within the central rectangle because their shape stay nearly
   * rectangular.
   *
   * - In the original function, a square lies in the center of the circle. An
   * argument has been added to this function to chose between a square and
   * a circle. We call this shape the "inner shape" of the circle.
   *
   * @param[in] tria
   * @param[in] p
   * @param[in] a
   * @param[in] b
   * @param[in] r
   * @param[in] R
   * @param[in] inner_circle
   *
   * @code "detailed_circle(&tria,&p,&a,&b,r,R,inner_circle)" @endcode
   *
   * | #   | Field         | Format                         | Required | Description                                                      |
   * |-----|---------------|--------------------------------|----------|------------------------------------------------------------------|
   * |  0  | &tria         | Triangulation <dim, spacedim>  | yes      | Triangulation used for the mesh                                  |
   * |  1  | &p            | Point<spacedim>                | yes      | Center of the circle                                             |
   * |  2  | a             | double                         | yes      | Rectangle width                                                  |
   * |  3  | &b            | double                         | yes      | Rectangle length                                                 |
   * |  4  | r             | double                         | yes      | Outer radius of the circle                                       |
   * |  5  | R             | double                         | yes      | Inner circle radius or inner square half-side                    |
   * |  6  | inner_circle  | true/false                     | yes      | True : the inner shape is a circle, False : it is a square       |
   * Example: @code "0.07 : 0.05 : 0.1 : 0.07 : 0.1 : 0.07 : 0.1 : 3 : 2 : 3 :
   * true" @endcode
   */
  void
  detailed_circle(Triangulation<2, 2> &tria,
                  const Point<2>      &p,
                  const double        &a,
                  const double        &b,
                  const double         r,
                  const double         R,
                  const bool           inner_circle);



  /// Width of the rectangular waveguide
  double rectangle_width;

  /// Length of the rectangular waveguide
  double rectangle_length;

  /// Outer radius of the cylindrical cavity
  double outer_radius;

  /// Inner length (radius if circle, half-side if square) of the central shape
  double inner_length;

  /// Height of the bottom cylinder
  double bottom_height;

  /// Height of the center section (waveguide embedded in cylinder)
  double middle_height;

  /// Height of the top cylinder
  double top_height;

  /// Number of slices of the extrusion of the bottom cylinder
  unsigned int bottom_resolution;

  /// Number of slices of the extrusion of the center cylinder
  unsigned int middle_resolution;

  /// Number of slices of the extrusion of the top cylinder
  unsigned int top_resolution;

  /// Shape of the inner region: true = circle, false = square
  bool inner_circle;
};


#endif
